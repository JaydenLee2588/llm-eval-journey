import torch
import torch.nn.functional as F

# 1. 定义输入张量 X (假设这是 1 个数据样本，包含 2 个数值特征)
# 形状: [1, 2]
X = torch.tensor([[1.0, -2.0]])

# ==========================================
# 方式一：纯手工计算底层数学公式 Y = XW + B
# ==========================================
# 定义权重矩阵 W (形状: [2, 3]，表示要把 2 个特征映射成 3 个新特征)
W = torch.tensor([[ 0.5,  0.1, -0.2],
                  [-0.5,  0.0,  0.8]])

# 定义偏置向量 B (形状: [3]，给每个新特征加上一个基础偏移量)
B = torch.tensor([0.1, 0.1, 0.1])

# 线性层运算：矩阵乘法 (@) 加上 偏置 (+)
# 计算过程: X 乘以 W 第一列 + 0.1 = (1.0*0.5 + -2.0*-0.5) + 0.1 = 1.6 ...以此类推
Y = X @ W + B
print("手工线性计算 Y:", Y) 
# 输出结果: tensor([[ 1.6000,  0.2000, -1.7000]])

# 激活函数运算：ReLU (粗暴但极度有效：把所有负数变成 0)
activated_Y = torch.maximum(Y, torch.tensor(0.0))
print("手工 ReLU 激活后:", activated_Y) 
# 输出结果: tensor([[ 1.6000,  0.2000,  0.0000]]) 
# (注意最后的 -1.7 被截断成了 0.0，这就是非线性)

# ==========================================
# 方式二：使用 PyTorch 现成的神经网络接口
# ==========================================
linear_layer = torch.nn.Linear(in_features=2, out_features=3)

# 强制把刚才手工设定的 W 和 B 塞给这个层，确保对比条件一致
# (PyTorch 底层为了计算优化，默认会将 W 矩阵转置，所以加上 .T)
linear_layer.weight.data = W.T
linear_layer.bias.data = B

# 框架只需一行代码即可完成 矩阵乘法 + 加偏置 + 激活函数
torch_output = F.relu(linear_layer(X))
print("PyTorch 框架输出:", torch_output) 
# 输出结果: tensor([[ 1.6000,  0.2000,  0.0000]]) (与手工计算完全一致)